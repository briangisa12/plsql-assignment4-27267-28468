SET SERVEROUTPUT ON;
-- Drop old tables so the script can be re-run
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('PRICE_CHANGE_LOG','STOCK_MOVEMENTS','PRODUCTS','SUPPLIERS')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
/

CREATE TABLE suppliers (
  supplier_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  supplier_name VARCHAR2(100) NOT NULL,
  phone         VARCHAR2(20),
  email         VARCHAR2(100),
  created_at    DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_suppliers      PRIMARY KEY (supplier_id),
  CONSTRAINT uq_supplier_name  UNIQUE (supplier_name),
  CONSTRAINT uq_supplier_email UNIQUE (email)
);

CREATE TABLE products (
  product_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  product_name  VARCHAR2(100) NOT NULL,
  category      VARCHAR2(50)  NOT NULL,
  supplier_id   NUMBER        NOT NULL,
  unit_price    NUMBER(10,2)  NOT NULL,
  qty_in_stock  NUMBER DEFAULT 0  NOT NULL,
  reorder_level NUMBER DEFAULT 10 NOT NULL,
  CONSTRAINT pk_products         PRIMARY KEY (product_id),
  CONSTRAINT fk_products_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
  CONSTRAINT uq_product_supplier UNIQUE (product_name, supplier_id),
  CONSTRAINT ck_price_positive   CHECK (unit_price > 0),
  CONSTRAINT ck_qty_nonnegative  CHECK (qty_in_stock >= 0),
  CONSTRAINT ck_reorder_level    CHECK (reorder_level >= 0)
);

CREATE TABLE stock_movements (
  movement_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  product_id    NUMBER       NOT NULL,
  movement_type VARCHAR2(3)  NOT NULL,
  quantity      NUMBER       NOT NULL,
  movement_date DATE DEFAULT SYSDATE NOT NULL,
  note          VARCHAR2(200),
  CONSTRAINT pk_stock_movements PRIMARY KEY (movement_id),
  CONSTRAINT fk_movement_product FOREIGN KEY (product_id) REFERENCES products(product_id),
  CONSTRAINT ck_movement_type   CHECK (movement_type IN ('IN','OUT')),
  CONSTRAINT ck_movement_qty    CHECK (quantity > 0)
);

CREATE TABLE price_change_log (
  log_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  product_id NUMBER       NOT NULL,
  old_price  NUMBER(10,2) NOT NULL,
  new_price  NUMBER(10,2) NOT NULL,
  changed_on DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_price_log PRIMARY KEY (log_id),
  CONSTRAINT fk_price_log_product FOREIGN KEY (product_id) REFERENCES products(product_id)
);